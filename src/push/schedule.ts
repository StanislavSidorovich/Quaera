import { isDue, type SkillState } from '../srs/scheduler';
import type { Progress } from '../srs/store';

/**
 * Когда будить человека напоминанием — и сколько тем к этому моменту подойдёт.
 *
 * Это единственная часть Web Push, ошибка в которой не даёт видимого отказа.
 * Всё остальное отказывает громко: нет разрешения — нет подписки, нет сети —
 * запрос падает, неверный VAPID — push-сервис отвечает 403. А неверное время
 * пробуждения выглядит нормально ровно до того момента, когда уведомление
 * приходит не тогда (или не приходит вовсе), — и заметить это можно только
 * прожив неделю с приложением. Отсюда гейт `npm run test:push-schedule`.
 *
 * ## Почему считает клиент, а не сервер
 *
 * У сервера есть таблица `progress` — казалось бы, он мог бы сам находить
 * просроченные навыки. Но тогда правило «что считается подошедшим» получило бы
 * вторую реализацию рядом с `isDue`, а обход паков — вторую рядом с `dueTotal`
 * в App.tsx. Две реализации одного правила расходятся, и расходятся молча:
 * ровно тот довод, по которому слияние прогресса живёт целым JSON, а не
 * разложено по строкам (см. supabase/migrations/0001_progress.sql).
 *
 * Плюс два следствия, каждое существеннее удобства:
 * - **работает без входа.** Прогресс лежит на устройстве, аккаунт опционален,
 *   и push, требующий войти, был бы напоминанием для тех, кто и так вернулся;
 * - **сервер знает строго меньше.** В базу уезжает отметка времени и
 *   непрозрачный endpoint push-сервиса — не история обучения.
 *
 * Сервер сравнивает `wakeAt` с `now()` и больше ничего не знает.
 *
 * ## Граница: что этот механизм ловит, а что нет
 *
 * Будильник заводится **на переход** «ничего не подошло» → «подошло, пока
 * приложение было закрыто». Уже просроченное на момент закрытия сюда
 * не попадает намеренно: человек только что видел это число на главной
 * и на иконке (бейдж `setAppBadge`, см. App.tsx), и напоминать ему через
 * час о том, что он час назад видел, — это докучание, а не напоминание.
 * Два механизма делят работу без пересечения: **бейдж ловит «ушёл,
 * не доделав», push ловит «подошло, пока тебя не было».**
 *
 * Отсюда же свойство, которого не пришлось добиваться отдельно: **потока
 * уведомлений быть не может.** Будильник взводится только при открытии
 * приложения, сервер гасит его отправкой — значит на каждое «открыл
 * приложение» приходится не больше одного уведомления, а забросивший
 * приложение получит ровно одно и тишину дальше.
 */

/**
 * Ближе этого срока будильник не заводится.
 *
 * Причина конкретная, а не «чтобы не частить». `review()` при провале
 * (оценка 1) ставит `dueAt` через **десять минут** — это возврат к теме
 * внутри той же сессии, и он адресован планировщику занятия, а не
 * напоминанию. Без нижней границы человек, закрывший приложение сразу
 * после неудачного ответа, получал бы push через десять минут — то есть
 * ровно про ту тему, с которой он только что встал.
 *
 * Двенадцать часов выбраны так, чтобы отсечь внутрисессионные сроки
 * и при этом не задеть настоящий минимальный интервал SRS: первый
 * успешный ответ даёт `intervalDays` 1 или 2, то есть срок не ближе
 * суток. Между десятью минутами и сутками есть где провести черту,
 * и полсуток — середина этого зазора, а не подобранное число.
 */
export const MIN_HORIZON_MS = 12 * 60 * 60 * 1000;

/**
 * Навыки, за которыми имеет смысл следить: начатые и существующие в паках.
 *
 * Оба условия ловят разное, и оба нужны.
 *
 * **`reps > 0`** — потому что `isDue` для незнакомого навыка возвращает `true`
 * (у него `dueAt` = начало эпохи), и без этого условия «подошло к повторению»
 * означало бы «есть непройденные темы», то есть было бы верно для всех и
 * всегда. Повторять можно только то, что хоть раз проходили.
 *
 * **Обход по списку из паков, а не по ключам `progress.skills`** — потому что
 * из хранилища никто не вычищает переименованные и удалённые навыки, и счёт
 * по ключам разбудил бы человека ради темы, которой в приложении нет.
 * Тот же дефект уже ловили на бейдже (замер на подсеянном прогрессе: три
 * просроченных ключа, реальных навыков из них один) и на восстановлении
 * занятия, которое хранит id шагов и пересобирается по текущим пакам.
 */
const trackedStates = (progress: Progress, skillIds: readonly string[]): SkillState[] =>
  skillIds.map((id) => progress.skills[id]).filter((s): s is SkillState => !!s && s.reps > 0);

/**
 * Сколько тем подойдёт к моменту `at`, если человек до тех пор не занимается.
 *
 * Точное число, а не оценка: SM-2 детерминирован, следующий срок навыка уже
 * записан в его состоянии, и без новых ответов он не изменится. То есть
 * уведомление может назвать количество, а не отделаться словом «пора».
 *
 * **Где оно всё же может соврать** — если человек занимался на другом
 * устройстве и синхронизировал прогресс: будильник этого устройства
 * останется взведённым со старым числом. Это цена того, что подпиской
 * владеет устройство, а не аккаунт (иначе push требовал бы входа —
 * см. шапку файла). Названо в комментарии, а не спрятано.
 */
export function dueCountAt(progress: Progress, skillIds: readonly string[], at: Date): number {
  return trackedStates(progress, skillIds).filter((s) => isDue(s, at)).length;
}

export interface WakeArming {
  /** Момент, когда сервер должен прислать уведомление, ISO. */
  wakeAt: string;
  /** Сколько тем подойдёт ровно к этому моменту — всегда ≥ 1. */
  dueCount: number;
}

/**
 * Что положить рядом с подпиской: когда будить и с каким числом.
 *
 * `null` — «будить не за чем», и это штатный ответ, а не отказ: так выглядят
 * и новичок без единого повторения, и человек, у которого всё просроченное
 * уже на экране, и тот, кто прошёл весь материал на месяцы вперёд. Вызывающий
 * обязан в этом случае **снять** прежний будильник, а не оставить старый:
 * иначе сброс прогресса или его импорт с другого устройства не гасили бы
 * уведомление, назначенное до них.
 *
 * Время суток не выбирается и часовой пояс не хранится — и это не упущение.
 * Интервалы SM-2 целые в днях, поэтому `dueAt` наследует **час, в который
 * человек занимался**: занимался вечером — и напомнит вечером. Любая попытка
 * «улучшить» это выбором удобного часа потребовала бы хранить пояс, то есть
 * узнать о человеке больше ради результата, который расписание и так даёт
 * само. Остаточный случай — тот, кто занимался среди ночи, получит ночное
 * напоминание; это цена, названная вслух, а не недосмотр.
 */
export function armWake(
  progress: Progress,
  skillIds: readonly string[],
  now: Date = new Date()
): WakeArming | null {
  const horizon = new Date(now.getTime() + MIN_HORIZON_MS);

  /*
   * Берём ближайший срок ЗА горизонтом, а не подтягиваем ближние сроки
   * к горизонту. Разница видна на частом наборе: одна тема провалена
   * (срок через десять минут), другая назначена через три дня. Подтягивание
   * разбудило бы через двенадцать часов ради темы, которую человек и так
   * видит на главной; выбор ближайшего дальнего срока разбудит через три
   * дня — когда действительно появится то, чего он не видел.
   */
  const upcoming = trackedStates(progress, skillIds)
    .map((s) => new Date(s.dueAt))
    .filter((d) => Number.isFinite(d.getTime()) && d >= horizon)
    .sort((a, b) => a.getTime() - b.getTime());

  const wake = upcoming[0];
  if (!wake) return null;

  /*
   * Число считается на момент пробуждения, а не на сейчас, и включает всё,
   * что подойдёт к тому времени, — не только сам разбудивший навык. Иначе
   * уведомление говорило бы «1 тема» там, где к утру подойдут четыре:
   * заниженное число здесь не осторожность, а неверный повод не открывать.
   */
  const dueCount = dueCountAt(progress, skillIds, wake);

  /*
   * dueCount ≥ 1 по построению: разбудивший навык на момент `wake` уже
   * подошёл. Проверка не защитная — она держит инвариант, на который
   * опирается текст уведомления («N тем»): если он когда-нибудь перестанет
   * выполняться, честнее не завести будильник, чем прислать «0 тем».
   */
  if (dueCount < 1) return null;

  return { wakeAt: wake.toISOString(), dueCount };
}
