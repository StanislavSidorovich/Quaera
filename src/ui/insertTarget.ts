export type InsertFn = (text: string) => void;

/**
 * Последнее сфокусированное поле ввода запроса — textarea в CodeEditor
 * или активный пропуск в FillTemplate (задание или песочница, оба держат
 * один и тот же редактор). Глобальный синглтон, а не проп через дерево:
 * SchemaSheet рисуется на самом верху (см. App.tsx), а поле ввода —
 * на несколько уровней глубже, внутри TaskView/Sandbox; прокидывать
 * колбэк через все промежуточные компоненты ради одного касания того
 * не стоит — как и `cached` в SchemaSheet.tsx, инстанс приложения один.
 *
 * Не снимается по blur: клик по колонке в шторке сам уводит фокус с поля,
 * и если снимать цель по blur, вставлять было бы уже некуда в тот самый
 * момент, когда шторка открыта. Снимается только при размонтировании
 * самого поля (уход с экрана задания) — см. clearInsertTarget.
 */
let target: InsertFn | null = null;

export function setInsertTarget(fn: InsertFn) {
  target = fn;
}

/**
 * Снимает цель, только если она всё ещё эта же функция. Иначе поле,
 * потерявшее фокус (человек кликнул в другое), стёрло бы цель, уже
 * переставленную на то, другое поле, — и вставлять стало бы некуда.
 */
export function clearInsertTarget(fn: InsertFn) {
  if (target === fn) target = null;
}

/**
 * true — текст ушёл в поле. false — активной цели нет (экран «Данные»,
 * где рядом нет редактора вовсе), и вызывающий обязан сделать что-то ещё —
 * TableDoc в этом случае копирует имя в буфер, как раньше.
 */
export function insertViaTarget(text: string): boolean {
  if (!target) return false;
  target(text);
  return true;
}
