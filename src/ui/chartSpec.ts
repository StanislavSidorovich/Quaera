import type { Preview, SqlValue } from '../engine/types';

/**
 * Решение о том, можно ли нарисовать этот результат графиком — и какой
 * график будет правдой.
 *
 * Здесь нет ни одной строчки рисования: модуль отвечает только на вопрос
 * «что честно показать по этим строкам», а SVG строится отдельно по готовому
 * описанию. Разделение не косметическое. Ошибка в рисовании видна глазом
 * за секунду, ошибка в решении — не видна никогда: график, который врёт,
 * выглядит ровно так же убедительно, как график, который не врёт, и человек
 * унесёт с него вывод, не заметив подмены. Поэтому все решения собраны
 * в одном файле, объяснены и закреплены гейтом (scripts/test-chart-spec.mjs).
 *
 * ГЛАВНЫЙ ПРИНЦИП, из которого выведено остальное:
 *
 *   График — вторая проекция той же таблицы, а не новый анализ.
 *   Строка в строку, в том же порядке. Ничего не суммируется, не
 *   досчитывается, не сортируется заново и не отбрасывается. Всё, что
 *   нельзя нарисовать в этих рамках честно, не рисуется вовсе.
 *
 * Почему именно так, а не «умный» график с автогруппировкой и топ-N.
 * Рядом с этим графиком всегда стоит таблица (переключатель, а не замена),
 * и в задании — ещё и эталон. Если картинка показывает не то же самое,
 * что таблица, человек сравнивает два разных объекта, не зная об этом.
 * Хуже: в тренажёре порядок строк — часто предмет самой задачи (ORDER BY
 * проверяется гейтом), и график, который тихо пересортировал результат
 * по величине, показал бы правильную картинку для неправильного запроса.
 *
 * ЧЕМ ГРАФИК ВРЁТ — семь способов, каждый закрыт ниже отдельным правилом:
 *
 * 1. Рисует кусок вместо целого. Превью обрезано до 200 строк (эталон —
 *    вообще до 8), и форма первых строк — не форма ряда. См. проверку
 *    rows.length < totalRows: обрезанный результат не рисуется никогда.
 * 2. Кодирует величиной то, что величиной не является: id, номер в рейтинге,
 *    год. У ранга 1 не «в три раза меньше», чем у ранга 3.
 * 3. Кладёт на одну ось несравнимые величины — выручку и проценты, штуки
 *    и рубли. Меньший ряд ложится в ноль и читается как «там ничего нет».
 * 4. Обрезает ось у столбцов. Столбец кодирует величину длиной, поэтому
 *    ось от нуля — часть кодирования, а не оформление (карточка
 *    dom-chart-choice, задание dom-056 — этому мы учим на соседнем экране).
 * 5. Соединяет линией то, между чем нет порядка: категории — не ряд.
 * 6. Ставит точки временного ряда равномерно, когда интервалы неравны, —
 *    наклон перестаёт быть скоростью.
 * 7. Соединяет линию через дыру, выдавая пропуск за плавный переход
 *    (это уже к рисованию: null обязан разрывать линию, а не сглаживаться).
 *
 * Правило выбора формы взято не из головы, а из карточки dom-chart-choice,
 * которую человек в этом же приложении читает: изменение во времени — линия,
 * сравнение категорий — столбцы. Приложение не имеет права нарушать теорию,
 * которой само учит; это тот же класс дефекта, что задание, не покрытое
 * теорией, — только заметить его ещё труднее.
 */

/**
 * Меньше трёх точек — сравнивать нечего: две точки задают ровно одну
 * прямую, и любая её крутизна — артефакт масштаба, а не свойство данных.
 * То же число, что у полос в ячейках (MIN_ROWS_FOR_BARS в ResultTable),
 * но обоснование своё, поэтому и константа своя.
 */
const MIN_POINTS = 3;

/**
 * Потолок для столбцов. Полсотни подписей ещё читаются в прокрутке, дальше
 * начинается частокол: сравнивать глазами такое нельзя, а можно только
 * оценивать распределение — а это другая форма (гистограмма), которую по
 * готовому результату запроса не построить, не пересчитав его. Пересчёт
 * запрещён главным принципом, поэтому здесь честнее отказать.
 * Линии потолок не нужен: пятьдесят две недели — это форма, а не частокол.
 */
const MAX_BARS = 50;

/**
 * Во сколько раз максимумы двух рядов могут отличаться, чтобы их всё ещё
 * имело смысл класть на одну ось. Ряд, который в двадцать пять раз мельче
 * соседа, уже прижат к нулю и сообщает «здесь ничего», хотя внутри него
 * может быть всё содержание. Это та же ошибка масштаба, что и обрезанная
 * ось, только с другой стороны: там движение раздуто, здесь спрятано.
 */
const MAX_SCALE_RATIO = 25;

/**
 * Слова в имени колонки, которые говорят про способ подсчёта, а не про
 * единицу измерения. Их выбрасывают перед сравнением имён (см. sameKind):
 * иначе avg_price и avg_units «совпали» бы по слову avg, то есть рубли
 * поехали бы на одну ось со штуками.
 */
const COUNTING_WORDS = new Set([
  'avg', 'mean', 'median', 'sum', 'total', 'tot', 'min', 'max', 'cnt', 'count', 'num', 'n',
  'prev', 'previous', 'cur', 'curr', 'current', 'new', 'old', 'first', 'last', 'top',
  'delta', 'diff', 'change', 'running', 'cum', 'cumulative', 'ma', 'mov', 'moving',
  'per', 'pct', 'percent',
]);

/** Колонки, которые не величина, сколько бы чисел в них ни лежало. */
const ID_LIKE = /(^|_)id$/i;
const RANK_LIKE = /(^|_)(rnk|rank|row_number|rownum|rowno|position|place)$/i;
const YEAR_LIKE = /(^|_)(year|yr)$/i;

/** Один ряд значений: колонка результата, взятая как есть, без пересчёта. */
export interface ChartSeries {
  column: string;
  /** По значению на строку результата, в порядке строк. null — дыра, не ноль. */
  values: (number | null)[];
}

/**
 * Набор рядов, которым разрешено делить одну ось, вместе с её границами.
 * Наборов может быть несколько — тогда это не слои одного графика,
 * а альтернативы: между ними переключаются, потому что на одной оси они
 * врали бы друг о друге. Первый набор — тот, что показывается по умолчанию.
 */
export interface ChartView {
  series: ChartSeries[];
  /** Нижняя граница оси. У столбцов всегда ≤ 0 — длина кодирует величину. */
  min: number;
  max: number;
}

export interface ChartSpec {
  kind: 'bar' | 'line';
  /** Подпись на каждую строку результата — ровно столько же, сколько строк. */
  labels: string[];
  /**
   * Только для линии: доля позиции точки на оси, 0..1, посчитанная по
   * настоящему времени. Пропуск месяца обязан быть виден как пропуск,
   * иначе наклон перестаёт означать скорость. У столбцов позиций нет —
   * там равные слоты, и это правда: категории равноправны.
   */
  positions?: number[];
  views: ChartView[];
}

/** Как значение выглядит в подписи. Слово NULL — то же, что в таблице рядом. */
function labelOf(v: SqlValue): string {
  if (v === null) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'string') return v;
  return '';
}

function tokensOf(name: string): Set<string> {
  return new Set(
    name
      .replace(/([a-zа-яё0-9])([A-ZА-ЯЁ])/g, '$1 $2')
      .split(/[^A-Za-zА-Яа-яЁё0-9]+/)
      .map((p) => p.toLowerCase())
      .filter((p) => p.length >= 2 && !/^\d+$/.test(p) && !COUNTING_WORDS.has(p))
  );
}

/**
 * Можно ли двум рядам делить ось. Два условия, и оба обязательны.
 *
 * Первое — общее слово в имени за вычетом слов о способе подсчёта.
 * Это не эвристика «на глазок», а самый прямой доступный признак того,
 * что перед нами одна и та же величина в разных условиях: promo_revenue
 * и base_revenue, target_revenue и actual_revenue, sell_in и sell_out,
 * units и prev_units. Именно такие пары и рисуют рядом. Словаря единиц
 * («revenue — это рубли») здесь нет намеренно: словарь пришлось бы вести
 * вторым источником правды и чинить на каждом новом задании, а общее слово
 * работает на любом имени и на любом языке.
 *
 * Правило отказывает в сомнительном случае, а не разрешает: units и ma4
 * общего слова не имеют и поедут разными видами, хотя вместе смотрелись бы
 * хорошо. Цена ошибки несимметрична — потерянный слой стоит одного клика,
 * а лишний слой на чужой оси стоит неверного вывода. Заодно это делает
 * честное имя колонки выгодным: units_ma4 склеится с units сам.
 *
 * Второе — сопоставимый масштаб. Штуки и «штук на точку» общее слово имеют
 * (units_per_outlet), но отличаются в восемьдесят раз, и второй ряд лёг бы
 * в ноль.
 */
function sameAxis(a: ChartSeries, b: ChartSeries): boolean {
  const ta = tokensOf(a.column);
  const tb = tokensOf(b.column);
  let shared = false;
  for (const t of ta) if (tb.has(t)) shared = true;
  if (!shared) return false;
  const ra = magnitude(a.values);
  const rb = magnitude(b.values);
  if (ra === 0 || rb === 0) return ra === rb;
  return Math.max(ra, rb) / Math.min(ra, rb) <= MAX_SCALE_RATIO;
}

function magnitude(values: (number | null)[]): number {
  let m = 0;
  for (const v of values) if (v !== null && Math.abs(v) > m) m = Math.abs(v);
  return m;
}

/**
 * Время из значения колонки. Понимает то, что реально возвращает датасет:
 * ISO-дату, месяц `2025-01` и год числом. Всё остальное временем не считается,
 * и результат поедет столбцами — это безопасная сторона ошибки.
 */
function timeOf(v: SqlValue): number | null {
  if (typeof v === 'number') {
    return Number.isInteger(v) && v >= 1900 && v <= 2100 ? Date.UTC(v, 0, 1) : null;
  }
  if (typeof v !== 'string') return null;
  const m = /^(\d{4})-(\d{2})(?:-(\d{2}))?/.exec(v);
  if (!m) return null;
  const month = Number(m[2]);
  const day = m[3] ? Number(m[3]) : 1;
  if (month < 1 || month > 12 || day < 1 || day > 31) return null;
  return Date.UTC(Number(m[1]), month - 1, day);
}

/**
 * Год как измерение, а не как величина. Столбец высотой «2025» — классика
 * автоматических графиков и чистая бессмыслица: год не количество.
 * Проверяем и по имени, и по форме значений (целые в разумном диапазоне,
 * строго по возрастанию и без повторов) — второе ловит `SELECT ... AS y`.
 */
function isYearColumn(name: string, values: (number | null)[]): boolean {
  const nums = values.filter((v): v is number => v !== null);
  if (nums.length < MIN_POINTS) return false;
  if (!nums.every((v) => Number.isInteger(v) && v >= 1900 && v <= 2100)) return false;
  if (YEAR_LIKE.test(name)) return true;
  return nums.every((v, i) => i === 0 || v > nums[i - 1]);
}

export function chartSpec(data: Preview): ChartSpec | null {
  const rows = data.rows;
  if (rows.length < MIN_POINTS) return null;

  /*
   * Обрезанный результат не рисуется. Форма первых двухсот строк — это форма
   * первых двухсот строк, а не ряда; на графике же ничто не сообщает, что
   * дальше что-то было. В таблице обрезка честно подписана снизу, картинка
   * такой подписи не имеет — читают её целиком и мгновенно.
   *
   * Сравниваем длину с totalRows, а не смотрим на флаг truncated: эталон
   * в задании режется до восьми строк вообще без флага (см. sql-worker.js),
   * и по флагу мы бы нарисовали восемь строк из шестнадцати как весь ответ.
   */
  if (data.totalRows > rows.length) return null;

  const dims: number[] = [];
  const measures: ChartSeries[] = [];

  data.columns.forEach((name, ci) => {
    const values = rows.map((r) => r[ci]);
    if (values.every((v) => v === null)) return;
    // Идентификатор и номер в рейтинге — не величина и не подпись:
    // рисовать их нельзя, а подписывать ими строки бессмысленно.
    if (ID_LIKE.test(name) || RANK_LIKE.test(name)) return;
    if (values.some((v) => v instanceof Uint8Array)) return;
    const nums = values.filter((v) => v !== null);
    const numeric = nums.length > 0 && nums.every((v) => typeof v === 'number' && Number.isFinite(v));
    if (!numeric) {
      dims.push(ci);
      return;
    }
    const asNums = values.map((v) => (v === null ? null : (v as number)));
    if (isYearColumn(name, asNums)) {
      dims.push(ci);
      return;
    }
    // Колонка почти вся из пропусков — рисовать по двум точкам нечего.
    if (nums.length < MIN_POINTS) return;
    measures.push({ column: name, values: asNums });
  });

  if (!dims.length || !measures.length) return null;

  /*
   * Чем подписывать строки. Если какое-то одно измерение само по себе
   * различает все строки — берём его, и правее: в SQL слева обычно стоит
   * крупная группировка, справа — точная (brand, product_name), а подпись
   * нужна точная. Если ни одно не различает — склеиваем все, и тогда
   * каждая строка всё равно остаётся отдельной точкой: это тот случай,
   * когда в результате несколько рядов (channel + month), и мы сознательно
   * не превращаем их в многосерийный график, а честно показываем строки.
   */
  let labelCols = dims;
  for (let i = dims.length - 1; i >= 0; i--) {
    const ci = dims[i];
    const seen = new Set(rows.map((r) => labelOf(r[ci])));
    if (seen.size === rows.length) {
      labelCols = [ci];
      break;
    }
  }
  const labels = rows.map((r) => labelCols.map((ci) => labelOf(r[ci])).join(' · '));

  /*
   * Раскладка величин по осям. Жадно: каждая следующая колонка идёт в первый
   * набор, где она совместима со всеми уже лежащими там, иначе заводит свой.
   * Порядок наборов — порядок колонок в результате, поэтому по умолчанию
   * показывается первая величина, а она в отчётах почти всегда главная.
   */
  const groups: ChartSeries[][] = [];
  for (const m of measures) {
    const target = groups.find((g) => g.every((s) => sameAxis(s, m)));
    if (target) target.push(m);
    else groups.push([m]);
  }

  /*
   * Форма. Линия — только там, где по горизонтали действительно время
   * и точки идут по возрастанию: линия обещает, что между соседями есть
   * непрерывный путь, и на категориях это обещание ложное. Два измерения
   * (channel + month) — тоже не линия: там несколько рядов, а не один.
   */
  let kind: 'bar' | 'line' = 'bar';
  let positions: number[] | undefined;
  if (labelCols.length === 1 && dims.length === 1) {
    const times = rows.map((r) => timeOf(r[labelCols[0]]));
    const ordered =
      times.every((t): t is number => t !== null) && times.every((t, i) => i === 0 || t > times[i - 1]!);
    if (ordered) {
      const ts = times as number[];
      const span = ts[ts.length - 1] - ts[0];
      kind = 'line';
      positions = ts.map((t) => (t - ts[0]) / span);
    }
  }

  if (kind === 'bar' && rows.length > MAX_BARS) return null;

  const views: ChartView[] = [];
  for (const series of groups) {
    let lo = Infinity;
    let hi = -Infinity;
    for (const s of series) {
      for (const v of s.values) {
        if (v === null) continue;
        if (v < lo) lo = v;
        if (v > hi) hi = v;
      }
    }
    if (lo === Infinity) continue;
    if (kind === 'bar') {
      /*
       * Ось столбцов всегда включает ноль — без исключений и без настройки.
       * Длина столбца и есть величина; обрезав низ, мы меняем не оформление,
       * а само сообщение (dom-056). Отрицательные значения при этом рисуются
       * вниз от нуля и потому законны: знак виден, соотношение сохранено.
       */
      lo = Math.min(0, lo);
      hi = Math.max(0, hi);
      if (lo === hi) continue; // все нули — рисовать нечего
    } else if (lo === hi) {
      // Ряд-константа: у линии нет размаха, растягивать нечего.
      lo = Math.min(0, lo);
      hi = Math.max(0, hi);
      if (lo === hi) hi = 1;
    }
    views.push({ series, min: lo, max: hi });
  }

  if (!views.length) return null;
  return { kind, labels, positions, views };
}
