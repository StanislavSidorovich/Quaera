import type { Track } from '../content/types';

/**
 * Знак приложения и знаки треков — там, где бокового меню нет.
 *
 * На телефоне постоянной навигации не существует вовсе (Sidebar скрыт до
 * 1024px), и шапка главной остаётся единственным местом, где приложение
 * может назвать себя и показать карту направлений. Раньше оно называло себя
 * словом, а карты не показывало совсем: перейти к треку можно было только
 * через карточки в теле экрана, и любая перестановка этих карточек рвала
 * единственную дорогу. Знак плюс полоска треков делают дорогу частью шапки —
 * то есть частью того, что на экране не двигается.
 *
 * Почему SVG, а не PNG из public/icons. Иконки приложения — растр, собранный
 * scripts/gen-icons.mjs, и он там не случайно: манифест PWA принимает только
 * файлы. В интерфейсе же знак обязан жить в потоке текста — тянуться за
 * кеглем (A+/A++), брать цвет темы и не мылиться на любом DPI. Это разные
 * задачи одного рисунка, и общее у них — форма, а не файл: три растущих
 * столбца и каретка запроса повторены здесь один в один по drawMark.
 */

/** Цвета столбцов знака — те же, что в scripts/gen-icons.mjs (drawMark). */
const MARK_BARS = [
  { x: 1, h: 6, fill: '#38bdf8' },
  { x: 7.5, h: 10, fill: '#818cf8' },
  { x: 14, h: 14, fill: '#4ade80' },
];

/**
 * Знак Quaera: три растущих столбца (данные) и каретка под ними (запрос).
 * Цвета столбцов жёсткие, а не переменные темы, — ровно по той же причине,
 * что и у цветов треков в styles.css: это опознавательный знак, и меняться
 * между светлой и тёмной темой ему нельзя. Каретка, наоборот, берёт цвет
 * текста: она часть рисунка, а не часть узнавания.
 */
export function QuaeraMark({ size = 28 }: { size?: number }) {
  return (
    <svg
      className="quaera-mark"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden
      role="presentation"
    >
      {MARK_BARS.map((bar) => (
        <rect key={bar.x} x={bar.x} y={17 - bar.h} width="4.5" height={bar.h} rx="1.2" fill={bar.fill} />
      ))}
      <rect x="1" y="19.5" width="12" height="2.6" rx="1.3" fill="currentColor" />
      <rect x="14.8" y="19.5" width="4.7" height="2.6" rx="1.3" fill="currentColor" opacity="0.4" />
    </svg>
  );
}

const glyphProps = {
  width: 18,
  height: 18,
  viewBox: '0 0 18 18',
  fill: 'none',
  stroke: 'currentColor',
  strokeWidth: 1.5,
  strokeLinecap: 'round' as const,
  strokeLinejoin: 'round' as const,
  'aria-hidden': true,
  role: 'presentation',
};

/**
 * Знак трека — рисунком, а не буквой.
 *
 * Буквы напрашивались (A, S, p, D — так трек и назван), но без подписи они
 * не опознаются: «S» и «D» одинаково подходят половине слов, а «p» и «D»
 * рядом читаются как один набор, а не как два разных направления. Рисунок
 * говорит, о чём трек, тем же способом, каким о нём говорит первое занятие:
 * вопрос под лупой, база, таблица, схема-звезда.
 *
 * Каждый знак рисуется на своём разрезе смысла, а не на инструменте:
 * «pandas» — это таблица в памяти, «модель данных» — связи между таблицами,
 * и различить их обязано быть можно, даже если оба показать серым.
 */
export function TrackGlyph({ track }: { track: Track }) {
  switch (track) {
    /*
     * Аналитика как профессия: лупа — «разобраться, что тут происходит».
     * Столбцы под лупой пробовались и отброшены: на 18px две колонки рядом
     * с окружностью читались как случайные чёрточки, а не как график.
     * Знак обязан опознаваться в шапке телефона, а не только в увеличении.
     */
    case 'domain':
      return (
        <svg {...glyphProps}>
          <circle cx="7.4" cy="7.4" r="5.2" />
          <path d="m11.3 11.3 4.4 4.4" strokeWidth="1.8" />
        </svg>
      );
    // SQL: база — цилиндр, самый узнаваемый знак запроса к хранилищу.
    case 'sql':
      return (
        <svg {...glyphProps}>
          <ellipse cx="9" cy="4.4" rx="6" ry="2.4" />
          <path d="M3 4.4v9.2c0 1.3 2.7 2.4 6 2.4s6-1.1 6-2.4V4.4" />
          <path d="M3 9c0 1.3 2.7 2.4 6 2.4s6-1.1 6-2.4" />
        </svg>
      );
    // pandas: таблица с шапкой и первой колонкой — это и есть DataFrame.
    case 'python':
      return (
        <svg {...glyphProps}>
          <rect x="2.5" y="3" width="13" height="12" rx="1.6" />
          <path d="M2.5 7h13" />
          <path d="M7 7v8" />
          <path d="M2.5 11h13" />
        </svg>
      );
    // Модель данных: звезда — факт в центре, измерения по краям.
    case 'model':
      return (
        <svg {...glyphProps}>
          <rect x="6.6" y="6.6" width="4.8" height="4.8" rx="1" />
          <rect x="1.8" y="1.8" width="3.2" height="3.2" rx="0.8" />
          <rect x="13" y="1.8" width="3.2" height="3.2" rx="0.8" />
          <rect x="1.8" y="13" width="3.2" height="3.2" rx="0.8" />
          <rect x="13" y="13" width="3.2" height="3.2" rx="0.8" />
          <path d="m5.2 5.2 1.4 1.4M12.8 5.2l-1.4 1.4M5.2 12.8l1.4-1.4M12.8 12.8l-1.4-1.4" strokeWidth="1.2" />
        </svg>
      );
  }
}
