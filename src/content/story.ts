import rawRu from './story.json';
import rawEn from './story.en.json';
import type { Track } from './types';
import type { Locale } from '../i18n/context';

/**
 * Проза сюжетной линии — единственная её часть, написанная руками.
 *
 * Сами миссии выводятся из графа навыков и никакого текста не содержат
 * (src/story/line.ts): их состав, порядок и оценка времени — следствие
 * предпосылок. Здесь лежит то, чего из графа не выведешь, — зачем человек
 * делает этот шаг и что у него после него появляется.
 *
 * **Почему отдельный файл, а не поле в паке.** Пак описывает навык и задание,
 * и всё в нём проверяется исполнением: эталон прогоняется движком, числа
 * в разборе сверяются с датасетом. Связка миссии не проверяется ничем
 * и относится не к заданию, а к их группе, которой в паке не существует
 * как сущности. Тот же довод, по которому вопросы песочницы лежат
 * в sandbox.json, а не в packs/ (см. шапку sandbox.ts).
 *
 * **Сопоставление позиционное, отпечаток — обязателен.** У миссии нет
 * собственного id в контенте: она выведена, а не написана, и её номер
 * меняется вместе с графом. Поэтому в русском файле у каждой миссии записан
 * состав навыков, и гейт test:story-line сверяет его с выведенной линией.
 * Без этого добавление одного навыка молча сдвинуло бы всю прозу на миссию
 * вперёд — и человек читал бы связку про соединения над заданиями про
 * оконные функции.
 *
 * **Перевод покрывает трек целиком или не покрывает вовсе.** Частичное
 * покрытие, как у паков, здесь бессмысленно: линия из восьми связок, где
 * три по-русски, читается хуже, чем линия без связок вообще. Трека нет
 * в story.en.json — англоязычный видит выведенные названия, ту же линию
 * без прозы, что и у ещё не написанных треков.
 */

export interface MissionStory {
  /** Название миссии. Не пересказ навыков, а то, чем этот этап работы занят. */
  title: string;
  /** Связка перед миссией: кто спрашивает и почему этот шаг идёт именно здесь. 2–3 предложения. */
  hook: string;
  /** Что у человека появилось. Показывается после прохождения — то есть как утверждение, а не как обещание. */
  outcome: string;
}

export interface TrackStory {
  /** Кто вы и где вы. Один раз наверху линии, не перед каждой миссией. */
  opening: string;
  /** Что теперь есть и что осталось. Виден, когда линия пройдена целиком. */
  ending: string;
  missions: MissionStory[];
}

/** Миссия, как она лежит в файле: та же проза плюс отпечаток состава (только в русском файле). */
type RawMission = MissionStory & { skills?: string[] };
type RawTrackStory = Omit<TrackStory, 'missions'> & { missions: RawMission[] };
type RawStory = { tracks: Partial<Record<Track, RawTrackStory>> };

const ru = rawRu as RawStory;
const en = rawEn as RawStory;

/**
 * Проза трека или null, если её ещё не писали.
 *
 * null — рабочее состояние, а не ошибка: движок линии готов для всех четырёх
 * треков, проза написана для одного. Экран в этом случае показывает линию
 * с выведенными названиями миссий.
 */
export function storyForTrack(track: Track, locale: Locale = 'ru'): TrackStory | null {
  const source = locale === 'en' ? (en.tracks[track] ?? ru.tracks[track]) : ru.tracks[track];
  return source ?? null;
}

/** Состав навыков миссии, как он записан в прозе. Нужен только гейту — экран сверкой не занимается. */
export function storyFingerprint(track: Track): string[][] {
  return (ru.tracks[track]?.missions ?? []).map((m) => m.skills ?? []);
}
