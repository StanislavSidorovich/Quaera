/**
 * Готовые запросы песочницы — «шпаргалка», зеркальная списку вопросов.
 *
 * Вопрос (content/sandbox.ts) — это ответ без готового решения: человек
 * упирается в пустой редактор и пишет сам. Рецепт — обратное: решение без
 * вопроса, рабочий скелет под свою задачу. Обе половины нужны, но по разным
 * поводам, и потому живут отдельными карточками, а не одним списком.
 *
 * **Почему это не разбавляет тренажёр готовыми ответами.** Опора — worked
 * example effect: новичку разбор готового решения даёт больше, чем поиск
 * вслепую. У него же есть обратная сторона — expertise reversal: тому, кто
 * уже умеет, готовый пример мешает. Отсюда единственное жёсткое правило:
 * **рецепты не появляются в потоке заданий никогда** — только в песочнице,
 * где нет ни эталона, ни SRS, и только по своему клику. В задании человек
 * по-прежнему вспоминает сам.
 *
 * Чтобы рецепт не оставался копипастом, у каждого названы **ручки** (что
 * в нём меняют под свой вопрос) и **одна ловушка** — то, что ломается,
 * если поменять не то. Ручки продублированы комментарием внутри кода:
 * панель остаётся на экране, а работать человек будет в редакторе, и
 * подсказка обязана уехать туда вместе с кодом.
 *
 * **Группы названы задачей, а не конструкцией.** Человек приходит с «мне
 * нужен топ-10», а не с «мне нужен ROW_NUMBER»; имя приёма он узнаёт внутри
 * рецепта, и связка «задача → приём» строится в эту сторону, а не в обратную.
 *
 * **Код зависит от локали, хотя это код** — по той же причине, что заготовка
 * редактора: комментарии внутри и есть единственная проза, и они же
 * единственное, что нуждается в переводе. Сам запрос обязан совпадать
 * пословно: гейт (scripts/verify-content.mjs) сверяет ru и en с точностью
 * до строк-комментариев и потому прогоняет только одну локаль.
 *
 * Что проверяет гейт помимо этого: каждый рецепт **реально выполняется**
 * обоими исполнителями на нашем датасете и возвращает непустой результат,
 * а SQL и pandas одного рецепта дают **один и тот же ответ**. Последнее —
 * не украшение: рецепт обещает «то же самое на другом языке», и без сверки
 * это обещание держалось бы на честном слове (тот же довод, что у карточки
 * сравнения инструментов в tools-compare.json).
 */
import raw from './recipes.json';
import type { Locale } from '../i18n/context';

/** Тема рецепта — форма задачи, а не имя приёма. Порядок задан в файле. */
export type RecipeGroup = 'slice' | 'trend' | 'compare' | 'join' | 'quality';

export interface RecipeText {
  title: string;
  /** На какой вопрос отвечает — одна строка, чтобы список читался без раскрытия. */
  intent: string;
  /** Что в рецепте меняют под себя. Дублируются комментарием внутри кода. */
  knobs: string[];
  /** Одна ошибка, которую делают чаще всего, — приглашение подумать, а не предупреждение. */
  pitfall: string;
}

export interface Recipe {
  id: string;
  group: RecipeGroup;
  /** Таблицы рецепта — те же имена, что в schema.json; сверяются гейтом. */
  tables: string[];
  /** Обязаны ли SQL и pandas дать один результат. false требует matchWhy. */
  match: boolean;
  matchWhy?: string;
  ru: RecipeText;
  en: RecipeText;
  code: {
    sql: Record<Locale, string>;
    python: Record<Locale, string>;
  };
}

export const RECIPES = raw.recipes as Recipe[];

/** Порядок групп — тот, в котором они впервые встречаются в файле. */
export const RECIPE_GROUPS: RecipeGroup[] = [...new Set(RECIPES.map((r) => r.group))];

export const recipeText = (r: Recipe, locale: Locale): RecipeText => (locale === 'en' ? r.en : r.ru);

export const recipeCode = (r: Recipe, env: 'sql' | 'python', locale: Locale): string => r.code[env][locale];
