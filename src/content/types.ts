/**
 * Контент — это данные, а не код.
 *
 * Приложение здесь плеер: оно ничего не знает про конкретные задания и умеет
 * проигрывать любой пак, удовлетворяющий этим типам. Отсюда два следствия:
 * задания можно пополнять без релиза приложения, и тот же формат позже
 * переиспользуется для треков pandas и модели данных — меняется движок
 * исполнения, а структура задания, подсказок и разбора остаётся той же.
 */

export type Track = 'sql' | 'model' | 'python' | 'domain';

export interface Skill {
  id: string;
  track: Track;
  title: string;
  /** Уровень в графе: 1 — фундамент, 4 — продвинутое. Нужен для порядка выдачи. */
  tier: 1 | 2 | 3 | 4;
  /** Что человек умеет, когда скилл освоен. Формулировка от первого лица, для самопроверки. */
  summary: string;
  /** Скиллы, без которых этот не берётся. Задаёт порядок, а не жёсткую блокировку. */
  prereqs: string[];
}

/**
 * Режим ввода. Один и тот же навык тренируется по-разному в зависимости
 * от того, где человек находится: predict читается одной рукой в дороге,
 * write требует стола или ландшафтной ориентации.
 */
export type TaskMode =
  /** Показан готовый запрос — предсказать результат. Проверка понимания без набора текста. */
  | 'predict'
  /** Запрос с пропусками — дописать фрагменты. Промежуточная ступень строительных лесов. */
  | 'fill'
  /** Полный ввод с нуля. */
  | 'write'
  /** Расставить шаги рассуждения по порядку. Единственный режим, работающий без исполнителя. */
  | 'order';

/**
 * Пункт задания на упорядочивание.
 *
 * Зачем этот вид задания вообще существует. `predict` проверяет узнавание:
 * человек видит готовые варианты и выбирает. Порядок действий узнаванием
 * не проверяется в принципе — правильную последовательность нельзя показать
 * среди неправильных, не выдав ответ. Между тем ровно последовательность
 * и составляет содержание трека `domain`: договориться о том, что считаем,
 * прежде чем считать; сверить базы, прежде чем сравнивать. Формат известен
 * (Parsons problems, Denny · Luxton-Reilly · Simon, 2008) и берётся ради
 * того же свойства, ради которого его берут в CS education: человек
 * производит ответ сам, а проверяется ответ по-прежнему точно.
 */
export interface OrderItem {
  /** Шаг рассуждения одной строкой. */
  label: string;
  /** Почему он стоит именно здесь. Показывается после решения — как `PredictOption.why`. */
  why: string;
}

export interface PredictOption {
  /** Текст варианта: либо описание результата, либо число. */
  label: string;
  correct?: boolean;
  /** Почему этот вариант выбирают — адресный разбор заблуждения. */
  why: string;
}

/**
 * Шаг многошагового задания — «посчитай, потом объясни, что получилось».
 *
 * Зачем отдельный тип, а не ещё один `TaskMode`. Одношаговое задание отвечает
 * на вопрос «умеешь ли ты это написать», и на нём разошлись два трека: `sql`
 * считает, `domain` интерпретирует. Связка «твой собственный результат → что
 * он значит» сильнее любой из половин, но она требует того, чего у `Task`
 * не было вовсе, — состояния между шагами. Массив шагов, а не поле-приставка
 * к обычному заданию, выбран сознательно: капстоун — тот же массив на пять
 * элементов, и тогда движок не переписывается второй раз, а получает новый
 * вид шага.
 *
 * **Правило, которое этот тип задаёт всему, что будет построено сверху:
 * шаг никогда не потребляет вывод человека — только эталон.** Варианты
 * интерпретации написаны против эталонного результата расчётного шага,
 * поэтому задание остаётся детерминированным и проверяемым гейтом
 * (`verify-content.mjs` исполняет эталон и сверяет с ним числа вопроса).
 * Ощущение «интерпретирую своё» при этом не теряется: когда расчёт сошёлся,
 * на экране стоят ровно те числа, которые человек получил сам. Без этого
 * правила капстоун стал бы первым контентом, правильность которого
 * не проверяет ничто, — тот же класс, из-за которого отклонена оценка
 * свободного текста по рубрике (ROADMAP §9).
 */
export type TaskStep =
  | {
      kind: 'compute';
      /** `predict` здесь невозможен: расчётный шаг тем и расчётный, что человек пишет код. */
      mode: 'write' | 'fill';
      /** Что должен вернуть запрос именно на этом шаге. Постановка задания целиком — в `Task.goal`. */
      goal: string;
      starter?: string;
      template?: string;
      blanks?: string[];
      solution: string;
      orderMatters?: boolean;
      hints: string[];
    }
  | {
      /**
       * Расставить пункты по порядку.
       *
       * **`items` записаны в правильном порядке** — отдельного поля с ответом
       * нет намеренно: два списка, которые обязаны соответствовать друг другу,
       * рано или поздно разъезжаются молча, и этот проект такое уже ловил
       * (шаблон `fill` против эталона). На экране пункты перемешиваются
       * плеером, детерминированно и заведомо не тождественно —
       * см. `shuffledOrder` в TaskView.
       */
      kind: 'order';
      question: string;
      items: OrderItem[];
      /** Бизнес-ситуация рядом с вопросом. Кода у этого вида шага не бывает. */
      scenario?: string;
      hints: string[];
      /** Постановка шага в многошаговом задании. У поднятого одношагового — `Task.goal`. */
      goal?: string;
    }
  | {
      kind: 'interpret';
      /** Вопрос к результату предыдущего шага. Он же и есть постановка — отдельного `goal` шагу не нужно. */
      question: string;
      options: PredictOption[];
      hints: string[];
      /**
       * Своя ситуация вместо результата предыдущего шага. В многошаговых
       * заданиях не заполняется никогда: интерпретировать нужно посчитанное.
       * Поля существуют потому, что одношаговый `predict` поднимается плеером
       * в этот же тип (см. resolveSteps в TaskView) — иначе на экране жили бы
       * две реализации одного экрана и однажды разошлись бы.
       */
      predictSql?: string;
      scenario?: string;
      /** Постановка шага, если она нужна помимо вопроса. У поднятого `predict` — `Task.goal`. */
      goal?: string;
    };

export interface Task {
  id: string;
  track: Track;
  /** Основной тренируемый навык. */
  skill: string;
  /** Дополнительные навыки, которые задание задействует — учитываются в SRS. */
  alsoTrains?: string[];
  level: 1 | 2 | 3 | 4 | 5;
  mode: TaskMode;
  title: string;
  /** Бизнес-постановка: кто и зачем спрашивает. Без неё задание вырождается в синтаксис. */
  brief: string;
  /** Что именно должен вернуть запрос: колонки, гранулярность, сортировка. */
  goal: string;
  /** Заготовка в редакторе для режима write. */
  starter?: string;
  /** Шаблон с пропусками `___` для режима fill. */
  template?: string;
  /** Значения пропусков по порядку — ими шаблон достраивается до solution. */
  blanks?: string[];
  /** Эталонный запрос. Ответ считается верным при совпадении результата, а не текста. */
  solution?: string;
  /** Важен ли порядок строк. По умолчанию нет — сравнение идёт как множеств. */
  orderMatters?: boolean;
  /** Запрос, показанный человеку в режиме predict. */
  predictSql?: string;
  /**
   * Бизнес-ситуация вместо запроса — для треков, где предсказывать нужно не
   * результат кода, а последствие решения (domain). Взаимоисключающа
   * с predictSql: у задания либо код, либо ситуация, и рендерятся они
   * по-разному — код моноширинным блоком, ситуация как текст.
   */
  scenario?: string;
  predictQuestion?: string;
  options?: PredictOption[];
  /** Вопрос режима `order`. Отдельно от `predictQuestion`: у задания либо варианты, либо порядок. */
  orderQuestion?: string;
  /** Пункты режима `order` — в правильном порядке (см. `TaskStep` kind `order`). */
  items?: OrderItem[];
  /** Раскрываются по одной. Первая — направление, последняя — почти решение. */
  hints: string[];
  /** Разбор после решения: не пересказ ответа, а идея, которая переносится на другие задачи. */
  explain: string;
  /**
   * Многошаговое задание. Взаимоисключающе с одношаговыми полями (`mode`
   * при этом остаётся и описывает расчётную часть — по нему считается
   * перекос по режимам ввода и рисуется пилюля режима).
   *
   * Задание с шагами засчитывается в SRS один раз, как и любое другое:
   * `correct` — когда верны все шаги, ошибки и подсказки складываются
   * по шагам. Шаг занятия при этом тоже один — счётчик «Задание 3 из 7»
   * не должен врать из-за внутреннего устройства задания.
   */
  steps?: TaskStep[];
}

/**
 * Карточка приёма — теория перед первой задачей на навык.
 *
 * Показывается один раз, при первой встрече с навыком, дальше — только по запросу.
 * Это не экономия места: новичку разобранный пример даёт больше, чем самостоятельная
 * попытка, но по мере роста навыка эффект переворачивается, и готовый образец
 * начинает мешать — человек копирует форму вместо того, чтобы восстанавливать её сам.
 *
 * Пять блоков идут в таком порядке намеренно: сначала зачем это в работе,
 * и только потом синтаксис. Приём, выученный без рабочего вопроса за спиной,
 * не вспоминается в тот момент, когда он нужен.
 */
export interface Lesson {
  skill: string;
  title: string;
  /** Какой вопрос заказчика этим закрывается. */
  why: string;
  /** Минимальная форма записи — скелет, а не исчерпывающий синтаксис. */
  form: string;
  /** Рабочий запрос на нашем датасете. */
  example: string;
  /** Что этот запрос отвечает, человеческими словами. */
  reads: string;
  /** Типичная ошибка: как её пишут. */
  wrong: string;
  /** Что при этом происходит — и почему это часто не видно. */
  wrongWhy: string;
  /** Проверка, которую стоит довести до рефлекса. */
  selfCheck: string;
}

/**
 * Перевод карточки приёма. Для sql `example` и `wrong` не переводятся — это
 * исполняемый код (или его точный аналог), а `form` — единственное поле
 * с русскими словами-плейсхолдерами («колонка», «таблица») вместо настоящего
 * синтаксиса, и его перевести нужно, иначе английская карточка покажет
 * русские слова посреди псевдокода.
 *
 * Для domain (и любого другого нетехнического трека) `example` и `wrong` —
 * не код, а обычная проза бизнес-сценария, поэтому здесь они переводимы
 * и опциональны: карточка без них просто оставляет русский текст, как и
 * с любым другим непереведённым полем (см. applyTranslation-логику).
 */
export interface LessonTranslation {
  skill: string;
  title: string;
  why: string;
  form: string;
  example?: string;
  reads: string;
  wrong?: string;
  wrongWhy: string;
  selfCheck: string;
}

/**
 * Вводная карточка трека — показывается один раз при первом входе, дальше
 * доступна по кнопке. Отвечает не на вопрос «что делать» (это уже умеет
 * `About`), а на вопрос «что это за инструмент вообще» — до того, как
 * человек увидит первую задачу без контекста, зачем она вообще существует.
 *
 * Это чистый текст без единого числа, которое можно было бы проверить
 * запросом к датасету, — зона «не проверяет ничто» из ROADMAP §2. Поэтому
 * пишется медленно и в последнюю очередь, отдельно от каркаса, который
 * выводит эти поля на экран.
 */
export interface TrackIntro {
  /** Что это за инструмент/область, 2–4 предложения. Без учебниковых определений. */
  what: string;
  /** Где это встречается в работе аналитика — конкретные ситуации, не абстракции. */
  where: string;
  /** Одна главная идея инструмента, которая переносится на весь трек. */
  idea: string;
  /** Чего инструмент не даёт — где он не поможет и придётся тянуться за другим. */
  limits: string;
  /** Тот же рабочий вопрос в соседнем треке — мост к остальным трём опорам. */
  bridge: string;
}

export interface Pack {
  id: string;
  track: Track;
  title: string;
  description: string;
  /** Вводная карточка трека. Необязательна: черновой трек и трек в начале наполнения могут быть без неё. */
  intro?: TrackIntro;
  /** 'draft' — граф навыков спроектирован, заданий и карточек ещё нет. Плеер не выдаёт по нему занятий. */
  status?: 'draft' | 'ready';
  version: number;
  /** Подписи уровней графа для карты навыков. Ключ — Skill.tier, приведённый к строке. */
  tierNames?: Record<number, string>;
  skills: Skill[];
  tasks: Task[];
}

/**
 * Перевод пака на английский — параллельный файл (`sql-core.json` →
 * `sql-core.en.json`), а не двуязычные поля внутри задания (см. ROADMAP §5:
 * иначе каждый батч контента дорожает вдвое немедленно). Содержит только
 * прозу: код (`starter`/`template`/`blanks`/`solution`/`predictSql`) не
 * переводится и не дублируется вовсе — это исполняемый, уже проверенный
 * гейтом текст, который ссылается на реальные значения датасета (бренды,
 * города — они в датасете по-русски и остаются такими в коде независимо
 * от языка интерфейса).
 *
 * Перевод может покрывать пак частично — id, которых нет в файле, просто
 * остаются на русском (см. applyTranslation в content/index.ts). Это то же
 * решение, что и с частично наполненным паком: точное покрытие проверяется
 * гейтом, а не структурой типа.
 */
export interface SkillTranslation {
  id: string;
  title: string;
  summary: string;
}

export interface TaskOptionTranslation {
  label: string;
  why: string;
}

/**
 * Перевод одного шага. Сопоставление позиционное, как и у вариантов ответа:
 * шаги — массив, и ключей у них нет. Поля объединены в один тип, а не разведены
 * по видам шага, потому что перевод не должен знать про виды: он переводит то,
 * что в шаге есть, и молчит про остальное.
 */
export interface TaskStepTranslation {
  /** Постановка расчётного шага. */
  goal?: string;
  /** Вопрос шага интерпретации. */
  question?: string;
  hints?: string[];
  options?: TaskOptionTranslation[];
  /** Пункты шага на упорядочивание. Порядок обязан совпадать с оригиналом — сопоставление позиционное. */
  items?: TaskOptionTranslation[];
}

export interface TaskTranslation {
  id: string;
  title: string;
  brief?: string;
  goal?: string;
  /** Для domain-заданий без исполнимого кода — см. Task.scenario. */
  scenario?: string;
  predictQuestion?: string;
  /** Вопрос режима order. */
  orderQuestion?: string;
  hints?: string[];
  explain?: string;
  /** Порядок обязан совпадать с Task.options — сопоставление позиционное, не по id. */
  options?: TaskOptionTranslation[];
  /** Порядок обязан совпадать с Task.items — тоже позиционно. */
  items?: TaskOptionTranslation[];
  /** Порядок обязан совпадать с Task.steps — тоже позиционно. */
  steps?: TaskStepTranslation[];
}

export interface PackTranslation {
  id: string;
  title?: string;
  description?: string;
  tierNames?: Record<number, string>;
  intro?: TrackIntro;
  skills?: SkillTranslation[];
  tasks?: TaskTranslation[];
}
