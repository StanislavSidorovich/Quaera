/**
 * Жанр блока `form`/`example`/`wrong` у треков без исполнителя: диаграмма
 * или проза.
 *
 * **Почему это решается содержимым, а не треком.** Первая редакция правки
 * (2026-08-23) ставила моноширинный блок всему domain и прозу всему model —
 * по признаку «какой трек». Признак оказался неверен в обе стороны сразу:
 * из шестидесяти полей domain двадцать — это не диаграммы, а цитаты
 * заказчика в поле `wrong` («Дистрибуция 94%» — сказано без указания…),
 * и моноширинный блок без переноса отправлял их в горизонтальную прокрутку
 * на телефоне, где в строку помещается 37 знаков. Обратная ошибка ждала бы
 * первую же диаграмму, написанную в model: она молча отрисовалась бы прозой,
 * и колонки разъехались бы ровно так, как разъезжались у domain до правки.
 * Трек — это про исполнимость кода, а жанр абзаца в нём не записан.
 *
 * **Что считается диаграммой.** Два независимых признака, любого достаточно:
 *
 * 1. **Рамочные символы** (`│ ─ ┌ └ ├ ┼ ┐ ┘ ┬ ┴`). Они рисуют связь между
 *    строками, то есть выкладка держится на положении знака в строке.
 *    Стрелка `→` в этот список НЕ входит намеренно: ею одинаково часто
 *    набран разбор внутри обычного предложения («→ SUM(units) из
 *    fact_sellout»), и по ней проза попадала бы в диаграммы.
 * 2. **Две и более строк с внутренним пробельным зазором** (`\S {2,}\S`) —
 *    подпись, столбец пробелов, вторая подпись. Одной такой строки мало:
 *    случайный двойной пробел встречается и в прозе, а колонка из одной
 *    строки — не колонка.
 *
 * Оба признака смотрят на выкладку, а не на длину: диаграмма шириной
 * в 30 знаков остаётся диаграммой, а абзац в 300 знаков — абзацем.
 *
 * Один и тот же разбор используют и вёрстка (LessonCard), и пятнадцатый
 * гейт (`npm run test:lesson-figure`). Держать его в двух местах нельзя:
 * гейт, повторяющий правило своими словами, со временем начинает проверять
 * не то, что происходит на экране.
 */

/** Символы, которыми рисуют связь между строками; стрелки сюда не входят (см. выше). */
const BOX_DRAWING = /[│─┌└├┼┐┘┬┴]/;

/** Подпись, зазор в два и более пробела, ещё подпись — след колонки, выровненной руками. */
const COLUMN_GUTTER = /\S {2,}\S/;

/**
 * Диаграмма ли это — то есть держится ли выкладка на положении знаков
 * в строке, и потому обязана ли рисоваться моноширинным блоком без переноса.
 */
export function isFigureBlock(text: string | undefined | null): boolean {
  if (!text) return false;
  if (BOX_DRAWING.test(text)) return true;
  return text.split('\n').filter((line) => COLUMN_GUTTER.test(line)).length >= 2;
}
