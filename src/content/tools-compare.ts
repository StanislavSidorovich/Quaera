/**
 * Один вопрос — три ответа разными инструментами. Карточка на экране
 * «С чего начать».
 *
 * Почему это отдельный файл контента, а не строки в i18n рядом с остальным
 * текстом онбординга: **здесь исполняемый код, а код в прозе не проверяется
 * ничем.** Все остальные обещания приложения прижаты сборкой — эталоны
 * заданий прогоняются по базе, числа в разборах сверяются с датасетом,
 * вопросы песочницы подтверждаются пробами. Три фрагмента, показанные
 * новичку первыми, оказались бы единственным местом, где код живёт
 * на честном слове и тихо протухает при первой правке генератора.
 *
 * Поэтому файл читают двое: экран и `scripts/verify-content.mjs`. Гейт
 * выполняет sql-фрагмент через sql.js, python-фрагмент — через Pyodide
 * с pandas (те же исполнители, что у заданий) и **сверяет их результаты
 * между собой**. Это ровно то утверждение, которое карточка делает вслух:
 * данные одни, инструменты разные, ответы обязаны сойтись. Если они
 * разойдутся, сборка упадёт — а не человек прочитает на первом экране
 * то, что тренажёр опровергает на всех остальных.
 *
 * У DAX исполнителя нет и не будет (движок закрытый, в браузер
 * не переносится), поэтому третий фрагмент помечен `runnable: false`
 * и гейт проверяет у него ровно это. **Асимметрия намеренная и названа
 * в самом тексте карточки** — не умолчание, которое читатель должен
 * заметить сам.
 *
 * Правки текста и кода здесь — как правки пака: после них
 * `npm run verify:content`.
 */
import raw from './tools-compare.json';
import type { Locale } from '../i18n/context';
import type { Track } from './types';

export interface ToolAnswer {
  /** Трек, чей это инструмент, — от него берутся название и цвет на экране. */
  track: Track;
  /** Есть ли у инструмента исполнитель. false только у DAX; см. комментарий выше. */
  runnable: boolean;
  /**
   * Одна строка на обе локали, в отличие от `note` и `question`, — и это
   * держится не соглашением, а гейтом: `code` обязан быть свободен
   * от кириллицы (см. verify-content.mjs).
   *
   * Причина в том, что переводить тут нечего ровно до тех пор, пока внутри
   * нет естественного языка. Первая версия DAX-фрагмента несла три строки
   * русских комментариев — и в английской локали карточка показывала
   * английский заголовок, английский вопрос, английское пояснение
   * и русский код между ними. Имя меры взято из пака model-core
   * (`Total Revenue`) по той же причине: то же имя человек увидит
   * в заданиях трека, а не второй вариант названия.
   */
  code: string;
  /** Что в этом ответе главное — читается рядом с кодом, а не вместо него. */
  note: Record<Locale, string>;
}

interface ToolsCompare {
  question: Record<Locale, string>;
  answers: ToolAnswer[];
}

const data = raw as ToolsCompare;

export const toolsCompareQuestion = (locale: Locale): string => data.question[locale];
export const toolsCompareAnswers: ToolAnswer[] = data.answers;
