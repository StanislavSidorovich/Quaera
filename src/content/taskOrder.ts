import type { Task } from './types';

/**
 * Порядок режима внутри одного уровня: от подсказанного к самостоятельному.
 * Общее место для планировщика (scheduler.ts, App.tsx) и линии кампании
 * (story/line.ts) — раньше жило только в line.ts, и подбор следующего задания
 * вне кампании сортировал исключительно по level, отчего первым в занятии
 * доставался write-вариант темы, а не predict.
 *
 * `order` встаёт вторым не по длительности, а по тому, что человек делает:
 * узнавание позади (ответ он производит сам), но материал ещё дан целиком —
 * ровно та ступень строительных лесов, между которой и `fill` разницы почти
 * нет по усилию и есть по тому, что проверяется: порядок против фрагмента.
 */
export const MODE_RANK: Record<Task['mode'], number> = { predict: 0, order: 1, fill: 2, write: 3 };

/**
 * Компаратор «образец → достраивание → с нуля»: уровень задаёт трудность
 * задачи, режим — сколько за человека сделали заранее, id — последний
 * тай-брейк ради детерминизма при полном совпадении первых двух ключей.
 */
export function compareTaskOrder(a: Task, b: Task): number {
  return a.level - b.level || MODE_RANK[a.mode] - MODE_RANK[b.mode] || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
}
