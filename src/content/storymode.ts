export interface StoryMessage {
  /** Кто пишет: имя и роль. Живой заказчик — дешёвый и уместный источник эмоции. */
  from: string;
  /** Текст сообщения. */
  text: string;
}

/**
 * Экран перед заданием.
 *
 * Один тип на две очень разные вещи — и это намеренно. Там, где задание просто
 * следующее в дне, здесь одна фраза без картинки и без заголовка; там, где
 * вводится новая идея (группировка, соединение, разложение на множители), —
 * полноценная теория с заставкой и разобранным примером. Разводить их в два
 * типа значило бы решать за автора, какой длины бывает подводка.
 *
 * Заставка необязательна и по умолчанию её нет: на дне из семи экранов
 * картинка над каждым перестаёт что-либо значить. Картинка открывает момент —
 * начало дня, новую идею, вывод, — а не сопровождает абзац.
 */
export interface StoryIntro {
  scene?: StoryScene;
  /** Заголовок экрана. Без него экран идёт одной прозой — так и задумано для коротких подводок. */
  title?: string;
  paras: string[];
}

export interface StoryStep {
  /** id существующего задания, которое крутится на этом шаге. */
  taskId: string;
  intro?: StoryIntro;
  /**
   * Реакция на сданное: одна реплика персонажа про то, что человек только что
   * получил. Появляется рядом с разбором решённого задания, своего экрана
   * не заводит.
   *
   * **Зачем.** Весь живой голос дня сидел на его концах — бриф утром, суждение
   * вечером, — а середина шла обучающей прозой, и три задания подряд
   * ощущались упражнениями, а не работой. Реплика возвращает середине пульс
   * дешевле любого экрана: мир заметил, что вы сдали.
   *
   * **Правило письма: реплика говорит о числе, а не о навыке.** «37 точек?
   * У нас их было под восемьдесят» — реакция; «отлично, вы освоили JOIN» —
   * похвала тренажёра, от которой история и отличается. Отсюда же
   * необязательность: заданию, чей результат никого в кампании не удивляет,
   * реплику придумывать не надо.
   */
  after?: StoryMessage;
  /**
   * Разговор между делом — экран перед подводкой этого шага, то есть между
   * двумя заданиями дня.
   *
   * **Зачем отдельная сущность, а не ещё один абзац подводки.** Подводка учит
   * и говорит голосом наставника; здесь никто не учит. Смысл беседы в том,
   * что человек получает факт из чужих рук — так, как факты и приходят
   * в работе: не из таблицы, а от того, кто был в поле. Дальше этот факт
   * либо подтвердится числами, либо нет, и в этом вся разница между
   * расследованием и упражнением.
   *
   * **Одна беседа на неделю.** Дважды — и это уже рубрика, а не случайность
   * коридора. Место выбирается по сюжету: в первой неделе разговор стоит
   * в среде, ровно там, где числа впервые упираются в потолок и подсказать
   * может только человек.
   */
  interlude?: { scene?: StoryScene; messages: StoryMessage[] };
}

export interface StoryMission {
  id: string;
  /**
   * Неделя кампании, которой принадлежит день.
   *
   * Полоса дела показывает пять делений и вопрос расследования — то есть
   * ровно одну неделю. Сложить все дни в один список значило бы получить
   * десять делений на 320 пикселях и один вопрос на две разные истории.
   * Сквозным при этом остаётся порядок: пятница первой недели ведёт
   * в понедельник второй тем же «следующим днём», и лестница конструкций
   * копится через границу недель, а не начинается заново.
   */
  week: string;
  /**
   * Короткая метка дня для полосы дела («Пн»). Полоса должна помещаться
   * на 320 пикселях в пять делений, поэтому метка именно короткая, а не
   * название дня целиком.
   */
  short: string;
  /**
   * Что этот день установил — одна строка в папку дела.
   *
   * Показывается не в своём дне, а в брифах следующих: смысл в том, чтобы
   * каждое утро начиналось с растущего списка уже известного. Пишется
   * как факт расследования, а не как перечень выученных приёмов: «продаж
   * в прайсе нет», а не «изучили SELECT».
   */
  found: string;
  /** Трек заданий — нужен, чтобы миссия шла в контексте его исполнителя и схемы. */
  track: Track;
  /** Контекстная строка брифа: место и время. Задаёт сцену одной строкой. */
  place: string;
  /**
   * Заставки трёх экранов дня, каждая необязательна (см. StoryIntro о том,
   * почему картинка не полагается каждому экрану).
   */
  scenes: { brief?: StoryScene; reflection?: StoryScene; hook?: StoryScene };
  /** Бриф как переписка: заказчик и руководитель. Ставит задачу дня и даёт человеческую фактуру. */
  messages: StoryMessage[];
  /** Задания дня по порядку, каждое со своей подводкой. */
  steps: StoryStep[];
  /**
   * Суждение после работы — не пересказ ответов, а вопрос «это уже ответ
   * заказчику?». Именно суждение, а не сводка, отличает историю от учебника
   * (см. разбор про выбор и суждение в исследовании вовлечения).
   */
  reflection: string[];
  /** Переход к следующему дню: что осталось нерешённым и куда ведёт сюжет. */
  hook: string[];
}

export interface StoryWeek {
  id: string;
  /**
   * Вопрос расследования — стоит над каждым экраном своей недели.
   *
   * Он существует ровно затем, чтобы на третьем задании вторника человек
   * помнил, зачем считает средние цены по брендам. Задание видно, а цель —
   * нет, и без напоминания неделя рассыпается на дюжину упражнений.
   */
  question: string;
}

