/**
 * Вопросы к данным для песочницы.
 *
 * Песочница — единственный экран приложения без эталона: человек пишет что
 * хочет и сам решает, верно ли получилось. Отсюда её главный риск, названный
 * ещё при планировании (ROADMAP §6, п. 2): не «не хватает возможностей»,
 * а пустое поле, перед которым нечего спросить. Этот список — ответ на него.
 *
 * Сами вопросы лежат в sandbox.json, а не здесь, по той же причине, по какой
 * там лежат паки заданий: контент правят руками и читает не только приложение,
 * но и гейт сборки (scripts/verify-content.mjs). JSON оба читают одинаково,
 * TS-модуль пришлось бы либо дублировать, либо разбирать текстом.
 *
 * Почему это отдельный файл, а не часть уже существующих:
 *
 *  - не i18n/ru.ts — там интерфейсная облицовка (кнопки, статусы), а это
 *    утверждение о датасете: что на этих данных у вопроса есть ответ. Такое
 *    утверждение обязано проверяться сборкой, как числа в разборах заданий;
 *  - не packs/*.json — у вопроса нет ни навыка, ни решения, ни режима ввода,
 *    он не попадает в SRS и ничему не назначает интервал. Положить его в пак
 *    значило бы протащить через все проверки заданий сущность, которая
 *    заданием не является.
 *
 * **Эталонов здесь нет намеренно, и это не упущение.** У каждого вопроса
 * в scripts/verify-content.mjs есть проба — запрос, доказывающий, что явление,
 * о котором спрашивают, всё ещё присутствует в данных. Пробы живут в гейте,
 * а не в контенте, по двум причинам: они не должны уезжать в бандл (иначе
 * готовый ответ лежит в исходниках экрана, который принципиально ничего
 * не проверяет), и гейт заодно следит, что списки не разъехались — у каждого
 * вопроса есть проба и наоборот. Захардкоженный список уже однажды промолчал
 * о непроверенном файле (см. хвост verify-content.mjs), поэтому связь
 * «вопрос ↔ проба» проверяется, а не поддерживается вручную.
 *
 * Каждый вопрос до написания текста прогнан по .cache/quaera.sqlite. Три
 * кандидата этот прогон отменил: оттока точек в данных нет вовсе (за полугодие
 * не потеряно ни одной), лаг отгрузки одинаков у всех дистрибьюторов
 * (6.3–6.7 дня), глубина скидки по брендам не различается (0.807–0.818
 * от прайса). Вопрос без явления в данных — это задание, которое учит тому,
 * чего нет, только без гейта, который бы это поймал.
 */
import raw from './sandbox.json';
import type { Locale } from '../i18n/context';

/** Тема вопроса — только для группировки списка на экране. */
export type SandboxGroup = 'overview' | 'trend' | 'distribution' | 'stock' | 'promo' | 'people' | 'quality';

export interface SandboxQuestion {
  id: string;
  group: SandboxGroup;
  /**
   * Где лежит ответ. Не подсказка к решению, а замена вопросу «с какой
   * таблицы вообще начать»: схема из двенадцати таблиц рядом, но какие
   * из них относятся к делу, по названиям видно не всегда.
   * Существование таблиц проверяется гейтом по schema.json.
   */
  tables: string[];
  ru: { title: string; question: string };
  en: { title: string; question: string };
}

/**
 * Порядок осмысленный и задан в файле, а не сортировкой на экране: сначала два
 * обзорных вопроса, на которых человек знакомится с данными и не может
 * ошибиться, дальше — по возрастанию аналитической сложности, последним —
 * качество данных, самый неприятный и самый рабочий из всех.
 */
export const SANDBOX_QUESTIONS = raw.questions as SandboxQuestion[];

/** Порядок групп в списке — тот, в котором они впервые встречаются среди вопросов. */
export const SANDBOX_GROUPS: SandboxGroup[] = [...new Set(SANDBOX_QUESTIONS.map((q) => q.group))];

/** Текст вопроса на текущей локали. Английский есть у всех: список короткий и переводится целиком, в отличие от паков. */
export const sandboxText = (q: SandboxQuestion, locale: Locale): { title: string; question: string } =>
  locale === 'en' ? q.en : q.ru;

/**
 * Что стоит в редакторе при первом входе.
 *
 * Не пустое поле и не заготовка под конкретный вопрос: минимальный запрос,
 * который сразу что-то возвращает. Первое нажатие «Выполнить» должно
 * показать данные, а не ошибку, — иначе человек начинает знакомство
 * с отладки собственной опечатки.
 *
 * У python вдобавок назван контракт result= (см. public/python-bootstrap.py):
 * в заданиях его вводит карточка приёма, а в песочницу можно попасть,
 * не пройдя ни одного задания.
 *
 * Зависит от локали, хотя это код: комментарии внутри — единственная проза
 * в заготовке, и они же единственное, что в ней нуждается в переводе. Тот же
 * урок, что снят на DAX-фрагменте в tools-compare.json: проза внутри блока
 * кода почти всегда и есть то, что делает блок нелокализованным.
 */
const STARTER: Record<Locale, Record<'sql' | 'python', string>> = {
  ru: {
    sql: 'SELECT * FROM fact_sellout LIMIT 20;',
    python: [
      '# Таблицы уже загружены как DataFrame: fact_sellout, dim_product, dim_customer, …',
      '# Ответ — то, что присвоено переменной result.',
      'result = fact_sellout.head(20)',
    ].join('\n'),
  },
  en: {
    sql: 'SELECT * FROM fact_sellout LIMIT 20;',
    python: [
      '# The tables are already loaded as DataFrames: fact_sellout, dim_product, dim_customer, …',
      '# Your answer is whatever you assign to result.',
      'result = fact_sellout.head(20)',
    ].join('\n'),
  },
};

export const sandboxStarter = (env: 'sql' | 'python', locale: Locale): string => STARTER[locale][env];

/**
 * Осталась ли заготовка нетронутой — проверяется по обеим локалям, а не
 * по текущей. Человек мог открыть песочницу по-русски и переключить язык,
 * не притронувшись к редактору: сравнение с одной локалью назвало бы чужой
 * стартовый текст его работой и предложило бы «Вернуть» то, что он не писал.
 */
export const isSandboxStarter = (env: 'sql' | 'python', code: string): boolean =>
  STARTER.ru[env] === code || STARTER.en[env] === code;
