/**
 * Русское склонение числительных. Без него счётчики выдают «43 заданий»
 * и «193 заданий» — правильно «43 задания» и «193 задания», потому что форма
 * зависит от последних одной-двух цифр, а не от величины числа.
 */
const plural = (n: number, one: string, few: string, many: string) => {
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  const mod10 = n % 10;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
};

