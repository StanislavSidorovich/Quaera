import type { SkillState } from '../srs/scheduler';
import type { Progress, TaskRecord } from '../srs/store';

/**
 * Слияние двух копий прогресса.
 *
 * Это фаза 1 синхронизации и единственная её часть, у которой цена ошибки
 * невосстановима. Всё остальное (таблица, RLS, вход, экраны) при поломке
 * даёт видимый отказ: не сохранилось, не вошёл, показало ошибку. Слияние
 * ломается молча — человек продолжает заниматься, а интервалы SRS уже
 * сдвинуты, и понять это можно будет только через недели, когда повторения
 * начнут приходить не тогда. Поэтому функция чистая, без сети, без React
 * и без localStorage: её можно прогнать тысячей случайных пар в гейте
 * (`npm run test:merge`) до того, как появится хоть одна строка клиента.
 *
 * **Почему не «побеждает свежая запись целиком».** Очевидное решение —
 * сравнить `savedAt` двух копий и взять новую — теряет данные ровно в том
 * сценарии, ради которого синхронизация и заводится: телефон и ноутбук
 * занимались разными треками, обе копии «свежие», и любая из них,
 * взятая целиком, стирает неделю работы на второй.
 *
 * **Форма решения — полурешётка (join semilattice).** Слияние
 * идемпотентно, коммутативно и ассоциативно: `merge(a, a) = a`,
 * `merge(a, b) = merge(b, a)`, `merge(merge(a, b), c) = merge(a, merge(b, c))`.
 * Это не теоретическое украшение, а то, что делает синхронизацию
 * безопасной без сервера-арбитра: порядок прихода копий перестаёт
 * влиять на результат, повторная отправка того же состояния ничего
 * не меняет, а три устройства сходятся к одному прогрессу независимо
 * от того, кто с кем слился первым. Все три свойства проверяются гейтом
 * на случайных данных, а не рассуждением здесь.
 *
 * **Разные поля сливаются по-разному, и это главное решение файла.**
 *
 * - *Состояние навыка* берётся **целиком у одной стороны**, а не по полю.
 *   Пара `ease`/`intervalDays` — результат конкретной цепочки повторений
 *   (см. `review`): взяв `ease` с телефона и `intervalDays` с ноутбука,
 *   получим состояние, которого не производил ни один реальный ответ,
 *   и следующий интервал будет посчитан из выдумки. Гейт проверяет это
 *   отдельным свойством: у каждого навыка в результате расписание
 *   побайтово совпадает с одним из входов.
 * - *Счётчики навыка* (`reps`, `lapses`) — максимум. Сумма двойным счётом
 *   удвоила бы общую историю, известную обеим сторонам; максимум в худшем
 *   случае теряет несколько повторений расходившейся ветки, но никогда
 *   не завышает. Ни один из двух не влияет на интервал — только на
 *   отображение и на `isUnlocked` (`reps > 0`), поэтому цена расхождения
 *   здесь косметическая, в отличие от расписания.
 * - *Запись о задании* сливается **по полю**, и это не противоречие
 *   предыдущему: `attempts`, `hintsUsed` и прочее ничего не планируют,
 *   из них не выводится ни один интервал. Смешанная запись «попыток
 *   с ноутбука, подсказок с телефона» — честная сумма знаний о задаче,
 *   а не выдуманное состояние.
 * - *`totalSolved` пересчитывается*, а не сливается. Это производное
 *   число: `applyAttempt` увеличивает его ровно при переходе задания
 *   в решённое, то есть оно всегда равно количеству записей с `solved`.
 *   Сложить два — получить двойной счёт по заданиям, решённым на обоих
 *   устройствах; взять максимум — разойтись с таблицей заданий.
 *
 * **Сброс прогресса.** У полурешётки нет удаления: то, что было в одной
 * копии, в слиянии всегда остаётся. Без отдельного решения кнопка «Сбросить
 * прогресс» превратилась бы в ложь — очищенное устройство при первой же
 * синхронизации получило бы всё обратно со второго.
 *
 * Первая версия делала сброс фильтром: `resetAt` сливался максимумом,
 * и всё, что старше метки, отбрасывалось с обеих сторон. Гейт эту версию
 * снял — она **не ассоциативна**, и вот почему это не формальность.
 * Слияние двух копий, ни одна из которых про сброс ещё не знает, успевает
 * сложить их счётчики в одну запись; третья копия приносит метку сброса,
 * но разделить уже сложенное нечем — а в другом порядке те же три копии
 * дают другой ответ. То есть итог зависел бы от того, чьё устройство
 * синхронизировалось первым, — ровно та невоспроизводимость, ради ухода
 * от которой всё и строится.
 *
 * Рабочая форма — **эпоха**: `resetAt` работает не фильтром, а меткой
 * поколения. Копии с одной эпохой сливаются как описано выше; копии
 * с разными не сливаются вовсе — целиком побеждает поколение с более
 * поздним сбросом. Лексикографическая пара (эпоха, содержимое) остаётся
 * полурешёткой, и все три свойства держатся точно, а не приблизительно.
 *
 * Цена решения названа прямо: устройство, занимавшееся **не зная о сбросе**,
 * при первой синхронизации эти занятия потеряет — они принадлежат стёртому
 * поколению. Это смысл кнопки «сбросить всё», а не побочный эффект:
 * альтернатива «сохранить занятия, сделанные после сброса по часам»
 * выглядит добрее ровно до того момента, когда выясняется, что часы
 * на двух устройствах разные и порядок слияния снова начинает решать.
 */

/** ISO-время или `null`; `null` считается древнее любой даты. */
const iso = (v: string | null | undefined): string => v ?? '';

const laterIso = (a: string | null | undefined, b: string | null | undefined): string | null => {
  const x = iso(a);
  const y = iso(b);
  const max = x > y ? x : y;
  return max === '' ? null : max;
};

const earlierIso = (a: string | null | undefined, b: string | null | undefined): string | null => {
  if (!a) return b ?? null;
  if (!b) return a;
  return a < b ? a : b;
};

/**
 * Ключ сравнения состояний навыка — ровно те поля, которые переносятся
 * целиком.
 *
 * `reps` и `lapses` в ключ намеренно не входят, хотя «больше повторений —
 * больше истории» звучит разумным правилом. Они сливаются максимумом,
 * то есть в результате оказываются не теми, что у победителя, — и если бы
 * сравнение на них опиралось, следующее слияние сравнивало бы уже другую
 * величину. Ассоциативность держится ровно на том, что ключ сравнения
 * состоит из полей, переживающих слияние без изменений.
 */
function skillKey(s: SkillState): string {
  return [
    iso(s.lastReviewedAt),
    String(s.intervalDays).padStart(6, '0'),
    s.ease.toFixed(4),
    s.dueAt,
    String(s.lastGrade ?? 0),
  ].join('|');
}

/**
 * Кто из двух описывает более позднее состояние навыка.
 *
 * Первым — время последнего повторения: устройство, занимавшееся вчера,
 * не должно быть перекрыто копией недельной давности. Дальше — сравнение
 * строк ключа, и это не «на всякий случай»: при равном времени нужен
 * какой-нибудь **детерминированный и не зависящий от порядка** ответ,
 * иначе `merge(a, b)` и `merge(b, a)` разойдутся. Порядок полей в ключе
 * подобран так, чтобы при равенстве времени выигрывал более длинный
 * интервал: два повторения в одну и ту же секунду на двух устройствах —
 * ситуация невозможная в реальности, но гейт генерирует и такие пары.
 */
const skillWinner = (a: SkillState, b: SkillState): SkillState => (skillKey(a) >= skillKey(b) ? a : b);

function mergeSkill(a: SkillState, b: SkillState): SkillState {
  const win = skillWinner(a, b);
  return {
    ...win,
    reps: Math.max(a.reps, b.reps),
    lapses: Math.max(a.lapses, b.lapses),
  };
}

function mergeTaskRecord(a: TaskRecord, b: TaskRecord): TaskRecord {
  return {
    attempts: Math.max(a.attempts, b.attempts),
    wrongAttempts: Math.max(a.wrongAttempts, b.wrongAttempts),
    hintsUsed: Math.max(a.hintsUsed, b.hintsUsed),
    solved: a.solved || b.solved,
    firstSolvedAt: earlierIso(a.firstSolvedAt, b.firstSolvedAt),
    lastAttemptAt: laterIso(a.lastAttemptAt, b.lastAttemptAt) ?? a.lastAttemptAt,
  };
}

/**
 * Слияние двух копий прогресса. Чистая функция: аргументы не меняются,
 * результат зависит только от них.
 */
export function mergeProgress(a: Progress, b: Progress): Progress {
  /*
   * Эпоха решается первой и решает всё: разные поколения не смешиваются,
   * младшее просто не участвует. Проигравшая сторона при этом не
   * возвращается как есть — она проходит через ту же нормализацию
   * (сортировка дней, пересчёт `totalSolved`), иначе `merge(a, старое)`
   * и `merge(a, a)` давали бы разные объекты и идемпотентность держалась
   * бы только на аккуратности вызывающего.
   */
  if (iso(a.resetAt) !== iso(b.resetAt)) {
    const winner = iso(a.resetAt) > iso(b.resetAt) ? a : b;
    return mergeProgress(winner, { ...winner, ...emptyEpoch(winner.resetAt) });
  }

  const skills: Record<string, SkillState> = {};
  for (const id of new Set([...Object.keys(a.skills), ...Object.keys(b.skills)])) {
    const sa = a.skills[id];
    const sb = b.skills[id];
    const merged = sa && sb ? mergeSkill(sa, sb) : (sa ?? sb);
    if (merged) skills[id] = merged;
  }

  const taskRecords: Record<string, TaskRecord> = {};
  for (const id of new Set([...Object.keys(a.taskRecords), ...Object.keys(b.taskRecords)])) {
    const ra = a.taskRecords[id];
    const rb = b.taskRecords[id];
    const merged = ra && rb ? mergeTaskRecord(ra, rb) : (ra ?? rb);
    if (merged) taskRecords[id] = merged;
  }

  /*
   * Дни активности — объединение, отсортированное и обрезанное теми же
   * 400 днями, что и в `applyAttempt`. Обрезка сохраняет самые новые,
   * поэтому она ассоциативна: день, выпавший на промежуточном слиянии,
   * заведомо старше четырёхсот сохранившихся и в итог не попал бы всё равно.
   */
  const activeDays = [...new Set([...a.activeDays, ...b.activeDays])].sort().slice(-400);

  return {
    version: 1,
    skills,
    taskRecords,
    activeDays,
    totalSolved: Object.values(taskRecords).filter((r) => r.solved).length,
    resetAt: a.resetAt ?? b.resetAt ?? null,
  };
}

/** Пустая копия той же эпохи — нейтральный элемент, см. mergeProgress. */
const emptyEpoch = (resetAt: string | null | undefined): Progress => ({
  version: 1,
  skills: {},
  taskRecords: {},
  activeDays: [],
  totalSolved: 0,
  resetAt: resetAt ?? null,
});
