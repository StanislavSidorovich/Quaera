/**
 * Сверка ответа текстом — третий путь проверки, рядом с исполнением
 * и выбором варианта.
 *
 * Нужен ровно там, где исполнителя нет и не будет: трек `model` учит DAX,
 * а движка DAX в приложении нет (ROADMAP §6 объясняет, почему собственный
 * симулятор фильтр-контекста — плохая идея: ошибка симулятора неотличима
 * от ошибки задания, и переписывать пришлось бы оба). Поэтому здесь нет
 * ни разбора формулы, ни модели вычисления — только сравнение того,
 * что человек вписал в пропуски, с эталонными фрагментами.
 *
 * Отсюда граница гарантий, и её стоит держать в голове при написании
 * контента: этот модуль отвечает на вопрос «совпало ли с эталоном»,
 * а не «верна ли мера». За верность самого эталона отвечает человек,
 * написавший задание, и закреплённые SQL-блоки в `verify-content.mjs`,
 * которые держат цитируемые числа.
 *
 * Почему сравниваются пропуски по отдельности, а не собранный текст
 * целиком: собранный текст даёт ответ «не сходится», а пропуски — «не
 * сходится второй», и человек видит, где именно ошибся. Проверка при этом
 * равносильна: гейт требует, чтобы шаблон с подставленными эталонными
 * значениями посимвольно давал `solution`, так что совпадение всех
 * пропусков и совпадение собранного текста — одно и то же утверждение.
 */

/**
 * Приведение фрагмента к сравнимому виду.
 *
 * Регистр снимается намеренно, и это свойство языка, а не поблажка:
 * в DAX имена функций, таблиц, колонок и мер регистронезависимы, поэтому
 * `CALCULATE` и `calculate` — буквально одна и та же формула. Различать
 * их значило бы проверять не понимание, а попадание по Shift.
 *
 * Пробелы внутри фрагмента сворачиваются по той же причине: `SUM( x )`
 * и `SUM(x)` — одна формула, а поле ввода в шаблоне узкое, и лишний пробел
 * там появляется от промаха пальцем, а не от непонимания.
 */
export const normalizeFragment = (s: string): string => s.trim().replace(/\s+/g, ' ').toLowerCase();

export interface BlanksVerdict {
  correct: boolean;
  /** Индексы пропусков, которые разошлись с эталоном, — по ним подсвечиваются поля. */
  wrongIndexes: number[];
  /** Сколько пропусков осталось пустыми: «не дописал» и «ошибся» — разные ответы. */
  emptyCount: number;
}

/**
 * Сверка вписанных фрагментов с эталонными.
 *
 * Пустой пропуск считается неверным, но выносится отдельным числом:
 * человеку, который не дописал формулу, нужен другой ответ, чем тому,
 * кто дописал неправильно.
 */
export function gradeBlanks(given: readonly string[], expected: readonly string[]): BlanksVerdict {
  const wrongIndexes: number[] = [];
  let emptyCount = 0;

  for (let i = 0; i < expected.length; i++) {
    const g = given[i] ?? '';
    if (!g.trim()) emptyCount++;
    if (normalizeFragment(g) !== normalizeFragment(expected[i])) wrongIndexes.push(i);
  }

  return { correct: wrongIndexes.length === 0, wrongIndexes, emptyCount };
}
