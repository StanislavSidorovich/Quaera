/**
 * Переезд ключей localStorage с `querium-*` на `quaera-*`.
 *
 * Приложение переименовано вместе с доменом (quaera.app), и вместе с именем
 * переименованы ключи хранилища. Само по себе это косметика — ключи человеку
 * не видны нигде, — но сделать её без переноса нельзя: у того, кто занимался
 * до переименования, весь прогресс, расписание SRS, незаконченное занятие,
 * сохранённые скрипты и согласие на 52 МБ рантайма лежат под старыми именами.
 * Без этого файла новая сборка открылась бы пустой, а старые данные остались
 * бы лежать рядом мусором, который никто уже не читает.
 *
 * **Переносится копированием, а не переименованием на месте**, и старый ключ
 * удаляется только после успешной записи нового. Запись в localStorage может
 * отказать (квота, приватный режим), и порядок «сначала удалил, потом не
 * записал» стоил бы прогресса целиком. Здесь худший исход — данные остались
 * под старым именем и переедут при следующем запуске.
 *
 * **Если новый ключ уже есть, старый просто удаляется.** Такое бывает у того,
 * кто открыл новую сборку, позанимался, а потом открылась вкладка со старой
 * из bfcache и записала старый ключ: свежее в этом случае новое, и
 * перезаписывать его прошлым состоянием нельзя.
 *
 * **Вызывается до первого чтения любого хранилища** — импортом первой строкой
 * в main.tsx. Порядок здесь не стилистический: модули вычисляются в порядке
 * импорта, и стоит поставить эту строку ниже `./App`, как часть хранилищ будет
 * прочитана раньше переноса.
 *
 * Файл одноразовый по смыслу, но убирать его нельзя ещё долго: человек,
 * не заходивший полгода, придёт со старыми ключами. Удалять — вместе
 * с очередной сменой `version` в самих хранилищах, не раньше.
 *
 * Под гейтом `npm run test:storage-migration` (входит в `npm run verify`).
 */

/** Пары «старый ключ → новый». Полный список ключей приложения: другого хранилища нет. */
export const STORAGE_RENAMES: ReadonlyArray<readonly [string, string]> = [
  ['querium-font-size', 'quaera-font-size'],
  ['querium-theme', 'quaera-theme'],
  ['querium-active-track', 'quaera-active-track'],
  ['querium-screen', 'quaera-screen'],
  ['querium-locale', 'quaera-locale'],
  ['querium-keyboard', 'quaera-keyboard'],
  ['querium-tokens', 'quaera-tokens'],
  ['querium.progress.v1', 'quaera.progress.v1'],
  ['querium.session.v1', 'quaera.session.v1'],
  ['querium.sandbox.v1', 'quaera.sandbox.v1'],
  ['querium.pyodide-consent.v1', 'quaera.pyodide-consent.v1'],
];

/** Минимум от Storage, который нужен переносу, — чтобы гейт мог подсунуть свой объект. */
export interface KeyValueStore {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
  removeItem(key: string): void;
}

/**
 * Переносит все старые ключи в новые. Возвращает имена перенесённых —
 * ради гейта; приложению возвращаемое значение не нужно.
 *
 * Идемпотентна: после успешного прохода старых ключей нет, и второй вызов
 * не делает ничего.
 */
export function migrateStorageKeys(store: KeyValueStore): string[] {
  const moved: string[] = [];
  for (const [oldKey, newKey] of STORAGE_RENAMES) {
    try {
      const value = store.getItem(oldKey);
      if (value === null) continue;
      if (store.getItem(newKey) === null) {
        store.setItem(newKey, value);
        moved.push(oldKey);
      }
      store.removeItem(oldKey);
    } catch {
      // Отказ на одном ключе не должен уносить остальные: прогресс и занятие
      // лежат под разными именами, и потерять оба из-за одного — хуже, чем
      // перенести что удалось и повторить попытку при следующем запуске.
    }
  }
  return moved;
}

try {
  migrateStorageKeys(localStorage);
} catch {
  // localStorage бывает недоступен целиком (жёсткие настройки приватности).
  // Приложение это переживает и без переноса — все чтения хранилища уже
  // обёрнуты в try/catch, — а вот падение здесь остановило бы загрузку.
}
