-- Подписки на push-напоминания: одна строка на устройство, без привязки к человеку.
--
-- Почему здесь нет user_id и нет ни одной ссылки на auth.users.
-- Прогресс живёт на устройстве, вход опционален (см. src/sync/), и push,
-- требующий войти, доставался бы ровно тем, кто и так возвращается.
-- Поэтому подпиской владеет устройство: сервер знает, КУДА постучать
-- и КОГДА, и не знает, кому это принадлежит и чему человек учится.
-- Расписание считает клиент (src/push/schedule.ts) — там же расписано,
-- почему не сервер: вторая реализация правила «что подошло» разошлась бы
-- с isDue молча, ровно как разошлось бы слияние, разложенное по строкам
-- (см. 0001_progress.sql).
--
-- Цена решения названа прямо: занимался на другом устройстве — будильник
-- этого останется взведённым со старым числом. Это осознанный размен
-- на работу без аккаунта, а не недосмотр.

create table if not exists public.push_subscriptions (
  -- Адрес, выданный push-сервисом браузера. Первичный ключ, потому что он
  -- уникален по своей природе: одна установка приложения в одном браузере —
  -- один endpoint, и повторная подписка возвращает тот же самый. Отсюда
  -- upsert по нему дедуплицирует сам, без отдельного «а не подписан ли уже».
  --
  -- Это URL-возможность (capability): знание адреса и есть право постучать.
  -- Поэтому таблица закрыта наглухо — см. политики ниже.
  endpoint text primary key,

  -- Ключи шифрования полезной нагрузки, выданные тем же браузером.
  -- Без них payload не зашифровать, то есть отправить можно только
  -- «пустой» push, который нечего показать.
  p256dh text not null,
  auth text not null,

  -- Когда будить. NULL — будильник снят: либо ещё не заводили, либо уже
  -- отправили, либо клиент сообщил, что будить не за чем (прогресс сброшен,
  -- всё пройдено на месяцы вперёд).
  --
  -- Именно отсюда берётся свойство «потока уведомлений быть не может»:
  -- взводит только клиент при открытии приложения, гасит отправка.
  -- Забросивший приложение получит ровно одно напоминание и тишину дальше.
  wake_at timestamptz,

  -- Сколько тем подойдёт к моменту wake_at. Считает клиент на своём
  -- прогрессе; сервер это число не проверяет и проверить не может —
  -- у него нет ни паков, ни истории ответов, и это к лучшему.
  due_count integer,

  -- Язык уведомления. Сам текст сервер НЕ присылает — его собирает
  -- service worker из своей таблицы строк (public/sw.js), а сюда уезжает
  -- только язык и число. Так у того, кто добыл ключ VAPID, нет способа
  -- показать человеку произвольный текст от имени приложения: он может
  -- ошибиться числом, но не подменить фразу.
  locale text not null default 'ru' check (locale in ('ru', 'en')),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- Наблюдение за доставкой. Подписка протухает молча: браузер снят,
  -- приложение удалено, push-сервис отозвал адрес. 404/410 от сервиса —
  -- однозначный ответ «этого адреса больше нет», такие строки удаляются
  -- сразу. Остальные отказы (сеть, 5xx) считаются, и после нескольких
  -- подряд строка тоже уходит: вечно стучать в мёртвый адрес — это
  -- расход квоты на того, кого уже нет.
  last_sent_at timestamptz,
  failures integer not null default 0
);

-- Выборка идёт ровно одним запросом раз в несколько минут: «кого пора
-- будить». Частичный индекс — по взведённым будильникам, потому что
-- снятые (wake_at is null) в этот запрос не попадают никогда, а их
-- со временем будет большинство.
create index if not exists push_subscriptions_wake_at_idx
  on public.push_subscriptions (wake_at)
  where wake_at is not null;

alter table public.push_subscriptions enable row level security;

-- Политик нет ни одной, и это не забывчивость.
--
-- RLS без политик означает «никому ничего»: ни анониму, ни вошедшему,
-- ни через publishable-ключ. Таблицу трогают только Edge Functions,
-- работающие под service_role, который RLS обходит.
--
-- Почему не разрешить анониму хотя бы insert, раз подписка ничья:
-- 1) select анониму нельзя ни в каком виде — endpoint это capability,
--    и открытый select раздал бы адреса всех устройств разом;
-- 2) insert без select всё равно оставляет открытую дверь на запись
--    в таблицу без единой проверки формы данных;
-- 3) update/delete «по знанию endpoint» пришлось бы разрешить всем
--    (проверить владельца нечем) — то есть безопасность свелась бы
--    к неугадываемости строки, а это не политика, а надежда.
-- Через функцию всё это решается один раз и в одном месте: она проверяет
-- форму, нормализует и пишет от service_role.
--
-- Форку, которому нужны напоминания, придётся завести обе функции у себя —
-- см. supabase/functions/ в репозитории и supabase/README.md.

create or replace function public.touch_push_updated_at()
returns trigger
language plpgsql
-- search_path пустой по той же причине, что у progress: функция выполняется
-- с правами определившего, и без явного пути её поведение зависело бы
-- от search_path вызывающего.
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists push_subscriptions_touch_updated_at on public.push_subscriptions;
create trigger push_subscriptions_touch_updated_at
  before update on public.push_subscriptions
  for each row execute function public.touch_push_updated_at();
